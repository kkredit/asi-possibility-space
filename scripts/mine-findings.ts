function leverLift(select: (s: Analysis['scenarios'][number]) => boolean) {
  const total = baseA.scenarios.reduce((a, s) => a + s.probability, 0);
  const sel = baseA.scenarios.filter(select);
  const selMass = sel.reduce((a, s) => a + s.probability, 0);
  const rows: { key: string; factor: string; state: string; pIn: number; pBase: number; lift: number }[] = [];
  for (const f of dataset.factors) {
    for (const st of f.states) {
      const inMass = sel.reduce((a, s) => a + (s.scenario[f.id] === st.id ? s.probability : 0), 0);
      const baseMass = baseA.scenarios.reduce((a, s) => a + (s.scenario[f.id] === st.id ? s.probability : 0), 0);
      const pIn = selMass > 0 ? inMass / selMass : 0;
      const pBase = total > 0 ? baseMass / total : 0;
      rows.push({ key: `${f.label} = ${st.label}`, factor: f.id, state: st.id, pIn, pBase, lift: pBase > 0 ? pIn / pBase : 0 });
    }
  }
  return { rows, selMass };
}
