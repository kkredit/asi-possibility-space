/** A copy of the baseline credences with one factor forced ~certain to a state. */
function believe(factorId: string, stateId: string, p = 0.98): Credences {
  const c: Credences = structuredClone(base);
  const dist = c[factorId];
  const others = Object.keys(dist).filter((s) => s !== stateId);
  const rem = 1 - p;
  const priorOthers = others.reduce((a, s) => a + dist[s], 0);
  c[factorId] = { [stateId]: p } as Record<string, number>;
  for (const s of others) c[factorId][s] = priorOthers > 0 ? rem * (dist[s] / priorOthers) : rem / others.length;
  return c;
}

/** Probability mass on catastrophic corners of each value dimension. */
function tailMass(a: Analysis) {
  const m = { extinction: 0, srisk: 0, agencyLoss: 0, squandered: 0 };
  for (const s of a.scenarios) {
    if (s.value.survival < -0.5) m.extinction += s.probability;
    if (s.value.suffering < -0.5) m.srisk += s.probability;
    if (s.value.agency < -0.5) m.agencyLoss += s.probability;
    if (s.value.flourishing < -0.5) m.squandered += s.probability;
  }
  return m;
}

/** Top action + its gain under a given credence set & weights. */
function topAction(cred: Credences, w: ValueVector) {
  const { ranked } = rankActions(dataset, cred, w, ev);
  return ranked[0];
}

